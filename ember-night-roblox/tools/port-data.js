#!/usr/bin/env node
'use strict';
// Ports the web game's content tables (glutnacht/js/data.js, lang.js, ui.js TIPS) to Luau data modules and writes
// JSON reference dumps for the Lune tests (docs/DESIGN.md §10.2).
//   node tools/port-data.js [path/to/glutnacht]
// Output:
//   src/shared/Sim/Data/{Weapons,Passives,Enemies,Heroes,Forge,Heat,Stages,Story,Achievements}.luau
//   src/shared/Lang/En.luau
//   tests/ref/data.json   (the same tables as JSON)
//   tests/ref/golden.json (reference values computed by the web code: curves, hash2, forge prices, stats)
// Object maps whose order matters (wave pools, event mixes) become arrays of { k = key, w = weight } so the Luau sim
// never iterates a hash table where order changes the outcome.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const WEB = path.resolve(process.argv[2] || path.join(ROOT, '..', 'glutnacht'));
const read = f => fs.readFileSync(path.join(WEB, f), 'utf8');

// ---------- load the web code in a sandbox ----------
const uiSrc = read('js/ui.js');
const tipsSrc = uiSrc.match(/const TIPS = \[[\s\S]*?\];/)[0];
const premiseSrc = uiSrc.match(/const PREMISE_SHORT = .*;/)[0];
const src = [read('js/util.js'), read('js/lang.js'), read('js/data.js'), read('js/game.js'), tipsSrc, premiseSrc,
  'this.__out = { WEAPONS, WEAPON_MAX, PASSIVES, MAX_WEAPONS, MAX_PASSIVES, ENEMIES, CHARS, SHOP, HEAT, STAGES, STORY,' +
  ' ACHIEVEMENTS, LANG_EN, TIPS, PREMISE_SHORT, ENEMY_COLORS, hpCurve, hpCurveBridged, xpFor, hash2, shopPrice,' +
  ' shopRefundValue, defaultSave, Store, Game, setLang };'].join('\n;\n');
const ctx = { console, Math, Object, Array, JSON, Number, String, Set, Map, localStorage: undefined };
vm.createContext(ctx);
vm.runInContext(src, ctx, { filename: 'glutnacht-bundle.js' });
const W = ctx.__out;

// ---------- Luau serializer ----------
const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;
const KEYWORDS = new Set(['and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in',
  'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while', 'continue', 'type', 'export']);
function str(s) {
  return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
}
function key(k) {
  return IDENT.test(k) && !KEYWORDS.has(k) ? k : '[' + str(k) + ']';
}
function num(n) {
  if (!Number.isFinite(n)) throw new Error('non-finite number');
  return String(n);
}
function lua(v, ind) {
  ind = ind || '';
  const ni = ind + '\t';
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return num(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'string') return str(v);
  if (typeof v === 'function') throw new Error('function in data');
  if (Array.isArray(v)) {
    if (!v.length) return '{}';
    const simple = v.every(x => typeof x !== 'object' || x === null);
    if (simple) return '{ ' + v.map(x => lua(x)).join(', ') + ' }';
    return '{\n' + v.map(x => ni + lua(x, ni) + ',').join('\n') + '\n' + ind + '}';
  }
  const ks = Object.keys(v).filter(k => v[k] !== undefined && typeof v[k] !== 'function');
  if (!ks.length) return '{}';
  const flat = ks.every(k => typeof v[k] !== 'object' || v[k] === null);
  const parts = ks.map(k => key(k) + ' = ' + lua(v[k], ni));
  const one = '{ ' + parts.join(', ') + ' }';
  if (flat && one.length + ind.length < 110) return one;
  return '{\n' + parts.map(p => ni + p + ',').join('\n') + '\n' + ind + '}';
}
// ordered pool: { bat: 2, slime: 3 } -> [{ k: 'bat', w: 2 }, ...]
const pool = o => Object.keys(o).map(k => ({ k, w: o[k] }));

const HEADER = '-- GENERATED by tools/port-data.js from glutnacht/js/*.js – do not edit by hand; re-run the generator.\n';
function write(rel, body) {
  const f = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, body);
  console.log('wrote', rel, '(' + body.length + ' bytes)');
}
const mod = (comment, fields) =>
  HEADER + '-- ' + comment + '\n\nreturn ' + lua(fields) + '\n';

// ---------- tables ----------
const weapons = {};
for (const id of Object.keys(W.WEAPONS)) {
  const d = W.WEAPONS[id];
  weapons[id] = { id, name: d.name, desc: d.desc, base: d.base, levels: d.levels, evo: d.evo };
}
write('src/shared/Sim/Data/Weapons.luau', mod('Weapons: base = level 1, levels[i] applies when reaching level i+1 (1-based: levels[1] -> level 2).', {
  byId: weapons, ORDER: Object.keys(W.WEAPONS), WEAPON_MAX: W.WEAPON_MAX, MAX_WEAPONS: W.MAX_WEAPONS,
}));

const passives = {};
for (const id of Object.keys(W.PASSIVES)) passives[id] = Object.assign({ id }, W.PASSIVES[id]);
write('src/shared/Sim/Data/Passives.luau', mod('Passive items.', {
  byId: passives, ORDER: Object.keys(W.PASSIVES), MAX_PASSIVES: W.MAX_PASSIVES,
}));

const enemies = {};
for (const id of Object.keys(W.ENEMIES)) enemies[id] = Object.assign({ id }, W.ENEMIES[id]);
// wire type index: ORDER position (1-based) ; 'night' (final boss sprite, no enemy entry) is appended
const enemyOrder = Object.keys(W.ENEMIES).concat(['night']);
write('src/shared/Sim/Data/Enemies.luau', mod('Enemy types. ORDER is the wire type index (1-based, "night" = final boss sprite). COLORS = ENEMY_COLORS.', {
  byId: enemies, ORDER: enemyOrder, COLORS: W.ENEMY_COLORS,
}));

const heroes = {};
for (const id of Object.keys(W.CHARS)) heroes[id] = Object.assign({ id }, W.CHARS[id]);
write('src/shared/Sim/Data/Heroes.luau', mod('Heroes (web CHARS).', { byId: heroes, ORDER: Object.keys(W.CHARS) }));

write('src/shared/Sim/Data/Forge.luau', mod('Forge upgrades (web SHOP), in shop order. Price/refund: Sim/Profile.luau.', { list: W.SHOP }));

write('src/shared/Sim/Data/Heat.luau', mod('Night levels. NOTE: index = heat + 1 (heat 0 is list[1]).', { list: W.HEAT }));

const stages = W.STAGES.map(s => {
  const o = Object.assign({}, s);
  o.waves = s.waves.map(w => Object.assign({}, w, { pool: pool(w.pool) }));
  o.events = s.events.map(e => (e.mix ? Object.assign({}, e, { mix: pool(e.mix) }) : e));
  o.surges = (s.surges || []).map(su => Object.assign({}, su, { pool: pool(su.pool) }));
  return o;
});
write('src/shared/Sim/Data/Stages.luau', mod('Lands (web STAGES). Pools and mixes are ordered arrays of { k = type, w = weight }.', {
  list: stages, ORDER: W.STAGES.map(s => s.id),
}));

write('src/shared/Sim/Data/Story.luau', mod('Story texts (German keys; translate with Lang.tr).', {
  premise: W.STORY.premise, ending: W.STORY.ending, PREMISE_SHORT: W.PREMISE_SHORT, TIPS: W.TIPS,
}));

const achs = W.ACHIEVEMENTS.map(a => ({ id: a.id, name: a.name, text: a.text, gold: a.gold, unlock: a.unlock }));
write('src/shared/Sim/Data/Achievements.luau', mod('Achievements (data only; the check functions live in Sim/Results.luau, keyed by id).', { list: achs }));

// ---------- language ----------
const en = W.LANG_EN;
const enBody = HEADER + '-- English translations (web LANG_EN): German source string -> English.\n\nreturn {\n' +
  Object.keys(en).map(k => '\t[' + str(k) + '] = ' + str(en[k]) + ',').join('\n') + '\n}\n';
write('src/shared/Lang/En.luau', enBody);

// ---------- JSON reference dumps ----------
const refData = {
  weapons, weaponOrder: Object.keys(W.WEAPONS), passives, passiveOrder: Object.keys(W.PASSIVES), enemies,
  enemyOrder, heroes, heroOrder: Object.keys(W.CHARS), shop: W.SHOP, heat: W.HEAT,
  stages: W.STAGES, achievements: achs, langCount: Object.keys(en).length, enemyColors: W.ENEMY_COLORS,
};
write('tests/ref/data.json', JSON.stringify(refData, null, 1) + '\n');

const G = W.Game;
const golden = { hpCurve: [], hpCurveBridged: [], xpFor: [], hash2: [], shopPrice: [], refund: [], stats: [], weapons: [] };
for (let m = 0; m <= 20; m += 0.25) {
  golden.hpCurve.push([m, W.hpCurve(m)]);
  golden.hpCurveBridged.push([m, W.hpCurveBridged(m)]);
}
for (let l = 1; l <= 80; l++) golden.xpFor.push([l, W.xpFor(l)]);
for (const [x, y, s] of [[0, 0, 7], [1, 0, 7], [0, 1, 8], [-3, 5, 9], [12, -40, 7], [-100, -100, 1], [77, 13, 0], [5, 5, 3], [-1, -1, 7], [300, -250, 9]]) {
  golden.hash2.push([x, y, s, W.hash2(x, y, s)]);
}
const shops = [{}, { might: 2 }, { might: 5, armor: 3, maxhp: 3 }, { revival: 1, amount: 1, luck: 2, cd: 2 }];
for (const shop of shops) {
  const save = { shop };
  golden.shopPrice.push({ shop, prices: W.SHOP.map(it => W.shopPrice(it, save)) });
  golden.refund.push({ shop, value: W.shopRefundValue(shop) });
}
W.Store.data = W.defaultSave();
const builds = [
  { char: 'aron', shop: {}, passives: [] },
  { char: 'mira', shop: { might: 3, cd: 2 }, passives: [{ id: 'hourglass', level: 3 }] },
  { char: 'brom', shop: { maxhp: 3, speed: 2, amount: 1 }, passives: [{ id: 'heart', level: 5 }, { id: 'boots', level: 2 }, { id: 'mirror', level: 2 }] },
  { char: 'lio', shop: { luck: 3, greed: 5, growth: 5 }, passives: [{ id: 'clover', level: 4 }, { id: 'candle', level: 1 }] },
];
for (const b of builds) {
  W.Store.data.shop = b.shop;
  const r = { char: b.char, passives: b.passives, weapons: [] };
  G.run = r;
  const s = G.computeStats(r);
  r.stats = s;
  const ws = [];
  for (const id of Object.keys(W.WEAPONS)) {
    for (const level of [1, 4, 8]) {
      for (const evo of level === 8 ? [false, true] : [false]) {
        const w = { id, level, evo };
        G.refreshWeapon(w);
        ws.push({ id, level, evo, st: w.st });
      }
    }
  }
  golden.stats.push({ build: b, stats: s, weapons: ws });
}
write('tests/ref/golden.json', JSON.stringify(golden, null, 1) + '\n');
